export default {
  async fetch(request, env) {
    const allowed = env.ALLOWED_ORIGIN || "https://soomabaradei-coder.github.io";
    const cors = {
      "Access-Control-Allow-Origin": allowed,
      "Access-Control-Allow-Methods": "POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type"
    };
    if (request.method === "OPTIONS") return new Response(null, { headers: cors });
    if (request.method !== "POST")
      return new Response("Method not allowed", { status: 405, headers: cors });

    const origin = request.headers.get("Origin") || "";
    if (origin && origin !== allowed)
      return new Response("Forbidden", { status: 403, headers: cors });

    let body;
    try { body = await request.json(); }
    catch { return new Response(JSON.stringify({ error: "bad_request" }), { status: 400, headers: { ...cors, "content-type": "application/json" } }); }

    let messages = Array.isArray(body.messages) ? body.messages : [];
    messages = messages
      .filter(m => m && (m.role === "user" || m.role === "assistant") && typeof m.content === "string")
      .slice(-20)
      .map(m => ({ role: m.role, content: m.content.slice(0, 4000) }));
    if (messages.length === 0 || messages[messages.length - 1].role !== "user")
      return new Response(JSON.stringify({ error: "bad_request" }), { status: 400, headers: { ...cors, "content-type": "application/json" } });

    const resp = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01"
      },
      body: JSON.stringify({
        model: env.MODEL || "claude-sonnet-5-5",
        max_tokens: 1536,
        system: SYSTEM,
        messages
      })
    });

    if (!resp.ok) {
      return new Response(JSON.stringify({ error: "upstream", status: resp.status }), { status: 502, headers: { ...cors, "content-type": "application/json" } });
    }
    const data = await resp.json();
    const text = (data.content || []).filter(b => b.type === "text").map(b => b.text).join("");
    return new Response(JSON.stringify({ text }), { headers: { ...cors, "content-type": "application/json" } });
  }
};
